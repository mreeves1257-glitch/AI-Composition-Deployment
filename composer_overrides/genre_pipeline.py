"""Isolated genre recognition and execution boundary. No audio/MIDI changes.

The existing genre interpreter is supplied as a callable. Only Classical is
enabled during this trial. This module does not silently substitute generic music.
"""
from dataclasses import dataclass
from pathlib import Path
import json

class GenrePipelineError(ValueError):
    pass

@dataclass(frozen=True)
class RecognizedGenre:
    name: str
    family: str
    profile_id: str
    definition: dict
    source_profile: dict

def recognize_genre(name, genre_root, *, allowed_genres=frozenset({"Classical"})):
    if name not in allowed_genres:
        raise GenrePipelineError("GENRE_NOT_ENABLED_FOR_TRIAL")
    root = Path(genre_root)
    index = json.loads((root / "index.json").read_text(encoding="utf-8"))
    relative = index["genre_to_family_file"].get(name)
    if not relative:
        raise GenrePipelineError("GENRE_NOT_REGISTERED")
    path = (root / relative).resolve()
    if not path.is_relative_to(root.resolve()):
        raise GenrePipelineError("INVALID_GENRE_PATH")
    profile = json.loads(path.read_text(encoding="utf-8"))["profiles"][name]
    definition = profile["musical_definition"]
    if profile["genre"] != name or definition.get("resolution_policy") != "AUTOMATIC_BASELINE_ALLOWED":
        raise GenrePipelineError("GENRE_PROFILE_NOT_AUTOMATIC")
    if not definition.get("profile_id"):
        raise GenrePipelineError("MISSING_PROFILE_ID")
    return RecognizedGenre(name, profile["family_name"], definition["profile_id"], definition, profile)

def execute_genre(recognized, interpreter, composer, *, creation_seed, available_instruments=None):
    """Strict ordered handoff: recognized -> existing interpreter -> composer.

    interpreter(recognized.definition, recognized.source_profile) must return a
    nonempty dict containing executable musical_plan. composer accepts plan
    and creation_seed. No MIDI or audio is generated by this adapter itself.
    """
    if recognized.name != "Classical":
        raise GenrePipelineError("CLASSICAL_ONLY_TRIAL")
    translated = interpreter(recognized.definition, recognized.source_profile)
    if not isinstance(translated, dict) or not isinstance(translated.get("musical_plan"), dict):
        raise GenrePipelineError("INTERPRETER_DID_NOT_RETURN_MUSICAL_PLAN")
    plan = translated["musical_plan"]
    required = ("tempo", "meter", "instrument_roles", "sections")
    if any(not plan.get(field) for field in required):
        raise GenrePipelineError("INCOMPLETE_CLASSICAL_PLAN")
    if not callable(composer):
        raise GenrePipelineError("COMPOSER_ADAPTER_REQUIRED")
    if available_instruments is None:
        raise GenrePipelineError("VERIFIED_INSTRUMENT_LIBRARY_REQUIRED")
    from universal_arrangement_handoff import handoff_interpreter_arrangement
    return handoff_interpreter_arrangement(recognized.name, plan, available_instruments, composer, creation_seed=creation_seed)
